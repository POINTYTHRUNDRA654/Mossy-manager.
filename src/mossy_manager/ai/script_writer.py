def _ini_tweak(
    preset: str,
    reasoning_summary: Optional[str] = None,
) -> str:
    """Generate an INI fragment for a known preset."""
    if preset not in _INI_PRESETS:
        available = ", ".join(_INI_PRESETS.keys())
        raise ValueError(f"Unknown INI preset '{preset}'. Available: {available}")

    desc = _INI_PRESET_DESCRIPTIONS.get(preset, preset)
    header_lines = [
        "; " + "=" * 68,
        f"; Mossy Manager INI Tweak — {desc}",
        f"; Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"; Paste these lines into Fallout4Custom.ini",
        f"; (My Documents\\My Games\\Fallout4\\Fallout4Custom.ini)",
    ]
    if reasoning_summary:
        header_lines.append(f"; AI Reasoning: {reasoning_summary[:100]}")
    header_lines.append("; " + "=" * 68)
    header = "\n".join(header_lines)

    body_lines: List[str] = []
    for key, val in _INI_PRESETS[preset].items():
        if key.startswith("["):
            body_lines.append(f"\n{key}")
        else:
            body_lines.append(f"{key}={val}")

    return header + "\n" + "\n".join(body_lines) + "\n"


