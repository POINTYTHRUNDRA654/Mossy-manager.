# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _safe_name(name: str) -> str:
    """Convert a human-readable name to a valid Pascal/file identifier."""
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if cleaned and cleaned[0].isdigit():
        cleaned = "Patch_" + cleaned
    return cleaned or "MossyPatch"


def _header_comment(
    script_type: str,
    description: str,
    reasoning_summary: Optional[str] = None,
    comment_char: str = "//",
) -> str:
    line = comment_char + " " + "=" * 70
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        line,
        f"{comment_char} Generated by Mossy Manager ScriptWriter — {now}",
        f"{comment_char} Script type : {script_type}",
        f"{comment_char} Description : {description}",
    ]
    if reasoning_summary:
        lines.append(f"{comment_char} AI Reasoning: {reasoning_summary[:120]}")
    lines.append(line)
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# xEdit Pascal script builders
# ---------------------------------------------------------------------------

def _xedit_conflict_patch(
    patch_name: str,
    plugins: List[str],
    conflicts: List[Dict[str, Any]],
    reasoning_summary: Optional[str] = None,
) -> str:
    """
    Generate a full xEdit Pascal script that:
    1. Creates a new patch plugin
    2. Loops over the conflicting plugins
    3. For each conflict, copies the winning record into the patch
    """
    safe = _safe_name(patch_name)

    # Build per-conflict forward-record block
    conflict_blocks: List[str] = []
    for i, conflict in enumerate(conflicts):
        resource = conflict.get("resource", f"unknown_{i}")
        mods = conflict.get("mods", [])
        category = conflict.get("category", "other")
        severity = conflict.get("severity", "medium")
        winner = mods[-1] if mods else "unknown"

        comment = (
            f"// [{severity.upper()}] {category}: '{resource}'\n"
            f"// Winner (loads last): {winner}\n"
            f"// Overridden by: {', '.join(mods[:-1]) if len(mods) > 1 else 'none'}"
        )
        conflict_blocks.append(
            f"  {comment}\n"
            f"  // TODO: Forward '{resource}' record from {winner} into {patch_name}.esp\n"
        )

    plugin_list_str = "\n".join(
        f"  AddRequiredMaster(patchPlugin, '{p.replace(chr(39), chr(39)+chr(39))}', False);"
        for p in plugins
    )
    conflict_section = "\n".join(conflict_blocks) if conflict_blocks else (
        "  // No specific conflicts to forward — verify manually."
    )

    header = _header_comment(
        "xEdit Pascal — Conflict Resolution Patch",
        f"Creates {patch_name}.esp and forwards winning records",
        reasoning_summary,
        comment_char="//",
    )

    return f"""{header}

unit {safe}_Script;

{{
  This script creates a conflict-resolution patch plugin for Fallout 4.
  Run it from the xEdit Script Runner (Tools > Apply Script).
  
  Mods in scope: {", ".join(plugins[:8])}{"..." if len(plugins) > 8 else ""}
  Conflicts to resolve: {len(conflicts)}
}}

var
  patchPlugin: IInterface;
  rec:         IInterface;
  masterFile:  IInterface;

function Initialize: integer;
begin
  Result := 0;
  AddMessage('[Mossy] Creating patch: {patch_name}.esp');

  patchPlugin := AddNewFileName('{patch_name}.esp', False);
  if not Assigned(patchPlugin) then begin
    AddMessage('[Mossy] ERROR: Could not create patch plugin');
    Result := 1;
    Exit;
  end;

  // Add required masters
{plugin_list_str}

  AddMessage('[Mossy] Patch plugin created. Forwarding records...');
end;

function Process(e: IInterface): integer;
var
  conflictWinner: IInterface;
  patchRec:       IInterface;
begin
  Result := 0;

  // Only process records from our conflicting plugins
  if not ContainsFile(e, patchPlugin) then Exit;

{conflict_section}

  // Copy record into patch and set override
  patchRec := wbCopyElementToFile(e, patchPlugin, False, True);
  if Assigned(patchRec) then
    AddMessage('[Mossy] Forwarded: ' + FullPath(patchRec));
end;

function Finalize: integer;
begin
  Result := 0;
  AddMessage('[Mossy] Done. Save {patch_name}.esp and place it AFTER all patched mods.');
end;

end.
"""


def _xedit_clean_itms(
    plugin_name: str,
    reasoning_summary: Optional[str] = None,
) -> str:
    """Generate an xEdit script that removes Identical-To-Master records."""
    safe = _safe_name(plugin_name)
    header = _header_comment(
        "xEdit Pascal — Clean ITM Records",
        f"Remove Identical-To-Master (ITM) records from {plugin_name}",
        reasoning_summary,
        comment_char="//",
    )
    return f"""{header}

unit {safe}_CleanITM;

{{
  Removes Identical-To-Master (ITM) records from {plugin_name}.
  ITMs are unnecessary overrides that inflate the plugin and cause
  compatibility issues with other mods.
  
  WARNING: Always back up your plugin before running this script.
}}

var
  removedCount: integer;

function Initialize: integer;
begin
  Result    := 0;
  removedCount := 0;
  AddMessage('[Mossy] Starting ITM clean for {plugin_name}');
end;

function Process(e: IInterface): integer;
begin
  Result := 0;
  if IsITM(e) then begin
    Remove(e);
    Inc(removedCount);
    AddMessage('[Mossy] Removed ITM: ' + FullPath(e));
  end;
end;

function Finalize: integer;
begin
  Result := 0;
  AddMessage('[Mossy] ITM clean complete. Removed ' + IntToStr(removedCount) + ' record(s).');
  AddMessage('[Mossy] Save the plugin and verify in xEdit.');
end;

end.
"""


def _xedit_esl_flag(
    plugins: List[str],
    reasoning_summary: Optional[str] = None,
) -> str:
    """Generate a script that ESL-flags a list of plugins to free plugin slots."""
    header = _header_comment(
        "xEdit Pascal — ESL-Flag Plugins",
        f"Flag {len(plugins)} plugin(s) as ESL to free slot usage",
        reasoning_summary,
        comment_char="//",
    )
    plugin_checks = "\n".join(
        f"  if (GetFileName(f) = '{p.replace(chr(39), chr(39)*2)}') then FlagAsESL(f);"
        for p in plugins
    )
    return f"""{header}

unit ESLFlag_Script;

{{
  ESL-flags the listed plugins so they no longer consume one of the
  255 available plugin slots.
  
  IMPORTANT: A plugin can only be safely ESL-flagged if it contains
  fewer than 2048 new Form IDs (new records added by the mod, not
  overrides). Verify this with xEdit before flagging.
  
  Plugins to flag ({len(plugins)}):
  {chr(10).join("  - " + p for p in plugins)}
}}

var
  i: integer;
  f: IInterface;

function Initialize: integer;
begin
  Result := 0;
  AddMessage('[Mossy] ESL-flagging {len(plugins)} plugin(s)...');
  for i := 0 to Pred(FileCount) do begin
    f := FileByIndex(i);
{plugin_checks}
  end;
  AddMessage('[Mossy] Done. Save all modified plugins.');
end;

function Process(e: IInterface): integer;
begin
  Result := 0;
end;

function Finalize: integer;
begin
  Result := 0;
end;

end.
"""


