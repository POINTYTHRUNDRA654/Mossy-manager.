def _bat_safe_launch(
    mo2_path: str = "C:\\Modding\\ModOrganizer2",
    f4se_path: str = "C:\\Games\\Fallout4\\f4se_loader.exe",
    reasoning_summary: Optional[str] = None,
) -> str:
    header = _header_comment(
        "Windows Batch — Safe F4SE Launch via MO2",
        "Launch Fallout 4 through F4SE from inside Mod Organizer 2",
        reasoning_summary,
        comment_char="REM",
    )
    return f"""{header}

@echo off
setlocal

REM ── Configuration ──────────────────────────────────────────────────────
set MO2_PATH={mo2_path}
set F4SE_EXE={f4se_path}

REM ── Plugin cap check ────────────────────────────────────────────────────
REM Count enabled plugins (lines starting with * in plugins.txt)
set PLUGINS_FILE=%APPDATA%\\..\\Local\\ModOrganizer\\Fallout4\\profiles\\Default\\plugins.txt
if not exist "%PLUGINS_FILE%" (
    echo [Mossy] Warning: Could not find plugins.txt at %PLUGINS_FILE%
    goto LAUNCH
)
for /f %%a in ('findstr /r "^[*]" "%PLUGINS_FILE%" ^| find /c /v ""') do set PLUGIN_COUNT=%%a
echo [Mossy] Enabled plugin count: %PLUGIN_COUNT%
if %PLUGIN_COUNT% GEQ 255 (
    echo [Mossy] ERROR: Plugin cap reached ^(%PLUGIN_COUNT%/255^). Game will not load!
    echo [Mossy] ESL-flag or merge plugins before launching.
    pause
    exit /b 1
)

:LAUNCH
REM ── Launch via F4SE ─────────────────────────────────────────────────────
if not exist "%F4SE_EXE%" (
    echo [Mossy] ERROR: F4SE not found at %F4SE_EXE%
    echo [Mossy] Download F4SE from https://f4se.silverlock.org/
    pause
    exit /b 1
)

echo [Mossy] Launching Fallout 4 via F4SE...
start "" "%F4SE_EXE%"
exit /b 0
"""


def _ps1_backup_profiles(
    mo2_path: str = "C:\\Modding\\ModOrganizer2",
    backup_root: str = "C:\\Modding\\Backups",
    keep: int = 5,
    reasoning_summary: Optional[str] = None,
) -> str:
    header = _header_comment(
        "PowerShell — Automated Profile Backup",
        "Back up all MO2 profiles and prune old backups",
        reasoning_summary,
        comment_char="#",
    )
    return f"""{header}

# Configuration
$MO2ProfilesPath = "{mo2_path}\\profiles"
$BackupRoot       = "{backup_root}"
$KeepCount        = {keep}

# Ensure backup root exists
if (-not (Test-Path $BackupRoot)) {{
    New-Item -ItemType Directory -Path $BackupRoot | Out-Null
}}

$timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

foreach ($profile in Get-ChildItem -Path $MO2ProfilesPath -Directory) {{
    $dest = Join-Path $BackupRoot ("$($profile.Name)_backup_$timestamp")
    Write-Host "[Mossy] Backing up profile: $($profile.Name)"
    Copy-Item -Path $profile.FullName -Destination $dest -Recurse

    # Prune: keep only the $KeepCount most recent backups for this profile
    $pattern  = "$($profile.Name)_backup_*"
    $existing = Get-ChildItem -Path $BackupRoot -Filter $pattern -Directory |
                Sort-Object Name -Descending
    $toDelete = $existing | Select-Object -Skip $KeepCount
    foreach ($old in $toDelete) {{
        Write-Host "[Mossy] Removing old backup: $($old.Name)"
        Remove-Item -Path $old.FullName -Recurse -Force
    }}
}}

Write-Host "[Mossy] Backup complete."
"""


# ---------------------------------------------------------------------------
# Public ScriptWriter class
# ---------------------------------------------------------------------------

class ScriptWriter:
    """
    Generate scripts for Fallout 4 mod management tasks.

    All methods return the script as a **string**.  Use ``write()`` to save
    to disk, or work with the string directly.

    Parameters
    ----------
    output_dir : Path, optional
        Default directory for ``write()`` calls.
    """

    XEDIT_SCRIPT_TYPES = frozenset(
        {"conflict_patch", "clean_itms", "esl_flag"}
    )
    INI_PRESETS = frozenset(_INI_PRESETS.keys())
    BATCH_TYPES = frozenset({"safe_launch", "backup_profiles"})

    def __init__(self, output_dir: Optional[Path] = None) -> None:
        self.output_dir = Path(output_dir) if output_dir else Path("./mossy_scripts")

    # ------------------------------------------------------------------ #
    #  xEdit Pascal scripts                                               #
    # ------------------------------------------------------------------ #

    def xedit_conflict_patch(
        self,
        patch_name: str,
        plugins: List[str],
        conflicts: Optional[List[Dict[str, Any]]] = None,
        reasoning: "Optional[ReasoningResult]" = None,
    ) -> str:
        """
        Generate a Pascal script that creates a conflict-resolution patch in xEdit.

        Parameters
        ----------
        patch_name : str
            Name for the generated ``.esp`` (e.g. ``"MyPatch"``).
        plugins : list of str
            Plugins involved in the conflicts.
        conflicts : list of dicts, optional
            Conflict dicts from ``ConflictResolver``.
        reasoning : ReasoningResult, optional
            Reasoning trace to embed in the script header.
        """
        rs = reasoning.conclusion if reasoning else None
        return _xedit_conflict_patch(patch_name, plugins, conflicts or [], rs)

    def xedit_clean_itms(
        self,
        plugin_name: str,
        reasoning: "Optional[ReasoningResult]" = None,
    ) -> str:
        """Generate a Pascal script that removes ITM records from *plugin_name*."""
        rs = reasoning.conclusion if reasoning else None
        return _xedit_clean_itms(plugin_name, rs)

    def xedit_esl_flag(
        self,
        plugins: List[str],
        reasoning: "Optional[ReasoningResult]" = None,
    ) -> str:
        """Generate a Pascal script that ESL-flags a list of plugins."""
        rs = reasoning.conclusion if reasoning else None
        return _xedit_esl_flag(plugins, rs)

    # ------------------------------------------------------------------ #
    #  INI tweaks                                                         #
    # ------------------------------------------------------------------ #

    def ini_tweak(
        self,
        preset: str,
        reasoning: "Optional[ReasoningResult]" = None,
    ) -> str:
        """
        Generate an INI fragment for *preset*.

        Valid presets: ``papyrus_logging``, ``archive_invalidation``,
        ``performance_high``, ``performance_low``.
        """
        rs = reasoning.conclusion if reasoning else None
        return _ini_tweak(preset, rs)

    # ------------------------------------------------------------------ #
    #  Batch / PowerShell                                                 #
    # ------------------------------------------------------------------ #

    def batch_safe_launch(
        self,
        mo2_path: str = "C:\\Modding\\ModOrganizer2",
        f4se_path: str = "C:\\Games\\Fallout4\\f4se_loader.exe",
        reasoning: "Optional[ReasoningResult]" = None,
    ) -> str:
        """Generate a .bat file that checks plugin count and launches via F4SE."""
        rs = reasoning.conclusion if reasoning else None
        return _bat_safe_launch(mo2_path, f4se_path, rs)

    def batch_backup_profiles(
        self,
        mo2_path: str = "C:\\Modding\\ModOrganizer2",
        backup_root: str = "C:\\Modding\\Backups",
        keep: int = 5,
        reasoning: "Optional[ReasoningResult]" = None,
    ) -> str:
        """Generate a PowerShell script that backs up all MO2 profiles."""
        rs = reasoning.conclusion if reasoning else None
        return _ps1_backup_profiles(mo2_path, backup_root, keep, rs)

    # ------------------------------------------------------------------ #
    #  Reasoning-driven generation                                        #
    # ------------------------------------------------------------------ #

    def from_reasoning(
        self,
        reasoning: "ReasoningResult",
        patch_name: str = "MossyAutoFix",
        plugins: Optional[List[str]] = None,
        conflicts: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, str]:
        """
        Automatically choose and generate the most relevant scripts based on
        a ``ReasoningResult`` from ``ModReasoner``.

        Returns a dict mapping script filename → script content.
        """
        scripts: Dict[str, str] = {}
        rules_fired = {s.rule for s in reasoning.steps}

        # Always generate the conflict-patch script if conflicts are present
        if conflicts or "ConflictRootCause" in rules_fired:
            scripts[f"{_safe_name(patch_name)}_conflict_patch.pas"] = (
                self.xedit_conflict_patch(patch_name, plugins or [], conflicts, reasoning)
            )

        # ESL-flagging when cap is approaching
        if "PluginCapHard" in rules_fired or "PluginCapWarning" in rules_fired:
            if plugins:
                scripts[f"{_safe_name(patch_name)}_esl_flag.pas"] = (
                    self.xedit_esl_flag(plugins, reasoning)
                )

        # Papyrus logging for crash / script-lag diagnoses
        if any(r in rules_fired for r in ("CrashDiagnosis", "ScriptLagDiagnosis")):
            scripts["enable_papyrus_logging.ini"] = self.ini_tweak(
                "papyrus_logging", reasoning
            )

        # Safe-launch batch if F4SE dependency is flagged
        if "F4SEDependency" in rules_fired:
            scripts["safe_launch.bat"] = self.batch_safe_launch(reasoning=reasoning)

        # Always include archive invalidation tweak as a best-practice extra
        if "MissingTextureDiagnosis" in rules_fired:
            scripts["archive_invalidation.ini"] = self.ini_tweak(
                "archive_invalidation", reasoning
            )

        # Fallback: generic conflict patch
        if not scripts:
            scripts[f"{_safe_name(patch_name)}_patch.pas"] = (
                self.xedit_conflict_patch(patch_name, plugins or [], conflicts, reasoning)
            )

        return scripts

    # ------------------------------------------------------------------ #
    #  File I/O                                                           #
    # ------------------------------------------------------------------ #

    def write(
        self,
        filename: str,
        content: str,
        output_dir: Optional[Path] = None,
    ) -> Path:
        """Write *content* to *filename* inside *output_dir* (or the default)."""
        dest_dir = Path(output_dir) if output_dir else self.output_dir
        dest_dir.mkdir(parents=True, exist_ok=True)
        out = dest_dir / filename
        out.write_text(content, encoding="utf-8")
        logger.info(f"Script written: {out}")
        return out

    def write_all(
        self,
        scripts: Dict[str, str],
        output_dir: Optional[Path] = None,
    ) -> List[Path]:
        """Write a dict of filename → content, returning the list of paths."""
        return [self.write(name, content, output_dir) for name, content in scripts.items()]
