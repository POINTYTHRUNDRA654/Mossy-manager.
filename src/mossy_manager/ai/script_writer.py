"""
ScriptWriter — Advanced script generation for Fallout 4 mod management.

Generates ready-to-use scripts from structured problem descriptions, optionally
driven by a ``ReasoningResult`` from ``ModReasoner`` so the scripts are
*motivated* by actual analysis rather than boilerplate.

Script types produced
---------------------
1. **xEdit Pascal scripts** (.pas)
   - Conflict-resolution patches (forward winning records)
   - Batch record editors (rename, flag, clean ITMs)
   - Dependency checkers

2. **MO2 INI-tweak scripts** (.ini fragment)
   - Papyrus log enable
   - Archive invalidation
   - Performance tuning presets

3. **Batch / PowerShell scripts** (.bat / .ps1)
   - Safe-launch wrappers (launch via F4SE, not Steam)
   - Profile backup automation
   - Plugin-cap check before launch

All generated scripts include a header comment explaining what they do and
*why* they were generated (linked to the reasoning trace when available).
"""

from __future__ import annotations

import logging
import re
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

# Import ReasoningResult lazily to avoid circular imports when used standalone
